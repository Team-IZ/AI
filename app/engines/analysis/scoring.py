# 재시험 판정 — **L1·L2 둘 다 통과해야 재시험이 아니다.**
#
# 2026-07-31 확정. PoC(scoring-config.js의 retest)는 "L1에서 막힌 문제만"으로
# 구현돼 있는데, 그건 사용자가 준 단일 예시에서 역산한 가설이었고 팀원도 주석에
# 가설이라고 표시해뒀다. 원 명세가 맞다 — **팀원 코드를 고쳐야 한다.**
#
#   L1 미달              → 재시험   (코드를 설명조차 못 함)
#   L1 통과 · L2 미달     → 재시험   (왜 그렇게 했는지를 못 댐)
#   L1·L2 통과 · L3 미달  → 재시험 아님 (보고서에만 상위 단계 미달로 표시)
RETEST_TRIGGER_AXES = ("L1", "L2")

def is_retest_target(passed_by_axis: dict[str, bool]) -> bool:
    """이 문제가 재시험 대상인가. 미도달 단계는 통과 안 한 것으로 본다."""
    return not all(passed_by_axis.get(axis, False) for axis in RETEST_TRIGGER_AXES)

def cap_for(hints_used: int) -> int:
    """힌트를 그만큼 썼을 때 받을 수 있는 최대 점수."""
    return HINT_CAPS.get(hints_used, min(HINT_CAPS.values()))


def autonomy_for(hints_used: int) -> str:
    return AUTONOMY.get(hints_used, "PARTIAL")


def axis_intent_block() -> str:
    """p04-4의 {axis_intent_block}. PoC 축 ID로 쓴다 — 모델이 그 ID로 답해야 한다."""
    return "\n".join(
        f"- {a['poc_id']} ({a['label']}): {a['question_intent']}" for a in AXES.values()
    )


def rubric_block(axis_code: str) -> str:
    """p04-5 채점용 {rubric_block}. 축 하나의 0~5점 정의."""
    axis = AXES[axis_code]
    lines = [f"{axis['poc_id']} ({axis['label']})"]
    lines += [f"  {score}: {text}" for score, text in sorted(axis["values"].items(), reverse=True)]
    return "\n".join(lines)